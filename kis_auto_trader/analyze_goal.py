def fee_drag(trips_per_year, fee=FEE_ROUND_TRIP, slip_per_side=0.0):
    """왕복 횟수에 붙는 연 비용%. 슬리피지는 한쪽당이므로 왕복에 2배."""
    return trips_per_year * (fee + 2 * slip_per_side)


def gross_per_trip(target_annual, trips_per_year, fee=FEE_ROUND_TRIP,
                   slip_per_side=0.0):
    """목표 연수익률을 내려면 왕복 한 번에 수수료 전 몇 % 를 벌어야 하나.

    복리로 나눈다. 단순히 목표/횟수 로 나누면 횟수가 많을 때 틀린다.
    """
    if trips_per_year <= 0:
        return float("inf")
    net = (1 + target_annual / 100) ** (1 / trips_per_year) - 1
    return net * 100 + fee + 2 * slip_per_side


def per_trip_actual(annual_pct, trips_per_year):
    """연수익률을 왕복당 실제 수익%로 바꾼다 (복리).

    수수료가 이익의 몇 %인지 보려면 이 값이 있어야 한다. 120일 주기는
    한 번 거래로 10.3% 를 담아서 수수료 0.21% 가 2% 밖에 안 된다.
    """
    if trips_per_year <= 0:
        return float("inf")
    return ((1 + annual_pct / 100) ** (1 / trips_per_year) - 1) * 100


def fee_share(annual_pct, trips_per_year, fee=FEE_ROUND_TRIP):
    """수수료가 왕복당 이익의 몇 %인가. 이익이 0 이하면 None."""
    got = per_trip_actual(annual_pct, trips_per_year)
    if got == float("inf") or got <= 0:
        return None
    return fee / got * 100


def beat_fee(grosses, fee=FEE_ROUND_TRIP):
    """수수료를 넘긴 거래 세기. (넘긴 수, 전체, 넘긴 것 평균, 전체 평균).

    '수수료 이상 벌 것만 거래한다' 가 가능한지 보는 재료다. 넘긴 것만
    고른 평균은 **성과가 아니라 상한**이다 - 결과를 보고 골랐으니까.
    """
    if not grosses:
        return (0, 0, None, None)
    over = [g for g in grosses if g > fee]
    return (len(over), len(grosses),
            st.mean(over) if over else None, st.mean(grosses))


def levered_year(year_pct, mult, borrow=BORROW_RATE):
    """달력 해 수익률에 레버리지를 걸었을 때의 어림값.

    **어림이다.** 정확히는 일수익률에 곱해야 하고 (복리 경로가 다르다)
    그건 analyze_aggressive.py 가 한다. 여기서는 해별 감각만 본다.
    """
    return year_pct * mult - borrow * (mult - 1)


