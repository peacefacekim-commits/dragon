def run(dates, panel, start, period):
    """start 부터 period 마다 갈아타며 끝까지. 일별 자산곡선과 거래횟수.

    종목 선정은 그 시점까지의 정보만 쓴다 (S.factor_score/universe_at).
    갈아탈 때 겹치는 종목을 안 건드리면 수수료가 덜 드는데, 그렇게 보면
    유리해지므로 보수적으로 전량 교체로 계산한다.
    """
    n = len(dates)
    cur, curve, trades = [], [], 0
    eq = 1.0
    di = start
    while di < n:
        if (di - start) % period == 0:
            cand = S.universe_at(panel, di, S.UNIVERSE_SIZE, S.MIN_PRICE)
            sc = [(x, c) for c in cand
                  if (x := S.factor_score(panel, c, di, "low_vol")) is not None]
            if len(sc) >= PICK:
                sc.sort(reverse=True)
                new = [c for _s, c in sc[:PICK]]
                if new != cur:
                    if cur:
                        eq *= (1 - FEE / 100)
                    trades += 1
                cur = new
        if cur:
            rs = []
            for c in cur:
                s = panel.get(c)
                if s is None:
                    continue
                j, jp = s.pos.get(di), s.pos.get(di - 1)
                if j is None or jp is None or not s.close[jp]:
                    continue
                rs.append(s.close[j] / s.close[jp] - 1)
            if rs:
                eq *= (1 + st.mean(rs))
        curve.append(eq)
        di += 1
    return curve, trades


def mdd(curve):
    """일별 곡선에서 최대낙폭. 평가손실을 포함한다 (거래만 보면 0 이 나온다)."""
    peak, worst = curve[0], 0.0
    for v in curve:
        peak = max(peak, v)
        worst = min(worst, v / peak - 1)
    return worst * 100


def rolling_windows(curve, span=DAYS_PER_YEAR):
    """겹치는 1년 창 전부. 시작일 운을 없애고 분포를 본다."""
    return [(curve[i + span] / curve[i] - 1) * 100
            for i in range(len(curve) - span)]


