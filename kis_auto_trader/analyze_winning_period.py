def daily_cum(done):
    """(날짜, 건수, 그날 원, 누적 원, 이긴 건수) 목록. 매도일 기준."""
    by = collections.OrderedDict()
    for t in done:
        d = t["sell_t"].strftime("%Y-%m-%d")
        a = by.setdefault(d, [0, 0.0, 0])
        a[0] += 1
        a[1] += t["won"]
        a[2] += 1 if t["won"] > 0 else 0
    out, cum = [], 0.0
    for d, (n, w, wins) in by.items():
        cum += w
        out.append((d, n, w, cum, wins))
    return out


def peak_of(done):
    """(최고 누적 원, 그 날짜, 그때까지의 건수). 누적은 매도 순서다."""
    cum, best, bd, bi = 0.0, 0.0, "", 0
    for i, t in enumerate(done):
        cum += t["won"]
        if cum > best:
            best, bd, bi = cum, t["sell_t"].strftime("%Y-%m-%d"), i + 1
    return best, bd, bi


