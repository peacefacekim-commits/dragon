def summarize(part):
    """(건수, 평균 net%, 중앙 net%, 승률%, 합계 원)."""
    if not part:
        return (0, 0.0, 0.0, 0.0, 0.0)
    ns = [t["net"] for t in part]
    return (len(part), st.mean(ns), st.median(ns),
            sum(1 for x in ns if x > 0) / len(ns) * 100,
            sum(t["won"] for t in part))


def perm_peak_p(wons, observed, n_perm=N_PERM, seed=SEED):
    """같은 건들을 무작위 순서로 섞어 최고 누적이 관측 이상인 비율.

    순서만 바꾸면 '실력' 은 사라지고 결과의 분포는 그대로다. 그래서
    "어느 시점에 그만큼 올라 있었다" 가 특별한지를 이걸로 판정한다.
    """
    rng = random.Random(seed)
    peaks, hits = [], 0
    for _ in range(n_perm):
        p = list(wons)
        rng.shuffle(p)
        c = m = 0.0
        for x in p:
            c += x
            if c > m:
                m = c
        peaks.append(m)
        if m >= observed:
            hits += 1
    return hits / n_perm, st.median(peaks)


def perm_firstk_p(nets, k, n_perm=N_PERM, seed=SEED):
    """앞 k 건의 평균이 관측 이상 나온 비율. k 는 미리 정해놓고 묻는다."""
    if k > len(nets):
        return None, None
    obs = st.mean(nets[:k])
    rng = random.Random(seed)
    hits = 0
    for _ in range(n_perm):
        q = list(nets)
        rng.shuffle(q)
        if st.mean(q[:k]) >= obs:
            hits += 1
    return obs, hits / n_perm


def deployment(dates, done, lo, hi, capital=CAPITAL):
    """그 구간 거래일마다 (열려 있던 포지션 원금 / 자본). (평균%, 최대%).

    **아무것도 안 들고 있던 거래일도 0% 로 센다.** 그 날을 빼면 평균이
    실제보다 높게 나오고, 그러면 '비중 맞춘 그냥보유' 기준선이 높아져서
    결론이 내 쪽에 유리해진다. 창 전체를 분모로 둔다.

    일별 잔고 기록이 없어서 만든 어림값이다. 하루 안에 사고팔며 같은
    돈을 두 번 쓰면 100% 를 넘을 수 있고, 실제로 B 구간이 그렇다.
    """
    per = collections.defaultdict(float)
    for t in done:
        d0 = t["buy_t"].strftime("%Y%m%d")
        d1 = t["sell_t"].strftime("%Y%m%d")
        for d in dates:
            if d0 <= d <= d1:
                per[d] += t["qty"] * t["buy"]
    win = [d for d in dates if lo <= d <= hi]
    if not win:
        return (0.0, 0.0)
    xs = [per.get(d, 0.0) / capital * 100 for d in win]
    return (st.mean(xs), max(xs))


def market_window(dates, panel, lo, hi):
    """그 구간 시장. (동일가중 평균 복리%, 중앙 종목 복리%).

    중앙값을 같이 내는 이유: 동일가중 평균은 몇 종목이 튀면 끌려간다.
    중앙 종목도 같이 올랐는지 봐야 '시장이 올랐다' 고 말할 수 있다.
    """
    idx = {d: i for i, d in enumerate(dates)}
    a, b = idx.get(lo), idx.get(hi)
    if a is None or b is None or b <= a:
        return None, None
    mean_c = med_c = 1.0
    for k in range(a + 1, b + 1):
        rets = []
        for s in panel.values():
            p, q = s.pos.get(k - 1), s.pos.get(k)
            if p is None or q is None:
                continue
            p0 = s.close[p]
            if p0:
                rets.append(s.close[q] / p0 - 1)
        if rets:
            mean_c *= 1 + st.mean(rets)
            med_c *= 1 + st.median(rets)
    return (mean_c - 1) * 100, (med_c - 1) * 100


def passive_match(market_pct, deploy_pct):
    """같은 비중으로 그냥 들고 있었다면. 어림값이다 (복리/구성 무시)."""
    return market_pct * deploy_pct / 100


def capture(actual_pct, passive_pct):
    """그냥보유가 낸 것의 몇 배를 따라갔나. 0 으로 안 나눈다.

    오를 때는 1 에 가까울수록 좋고, 내릴 때는 0 에 가까울수록 좋다.
    monitor.py 의 포착률과 뜻이 반대라서 그 문턱을 쓰지 않는다.
    """
    if not passive_pct:
        return None
    return actual_pct / passive_pct


def window_part(done, lo, hi):
    """매도일이 그 구간에 든 거래만."""
    return [t for t in done
            if lo <= t["sell_t"].strftime("%Y%m%d") <= hi]


