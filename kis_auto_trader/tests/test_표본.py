def geo(vals):
    """연수익률% 목록의 기하평균%."""
    acc = 1.0
    for v in vals:
        acc *= (1 + v / 100)
    return (acc ** (1 / len(vals)) - 1) * 100


def n_independent(n_windows, spacing_days, window_days):
    """겹치는 창 n개가 실제로 몇 개 몫인가.

    창이 window_days 길이인데 spacing_days 마다 새로 시작하면, 서로
    안 겹치는 창은 전체 기간 / window_days 개다. 전체 기간은
    (n_windows - 1) * spacing_days + window_days 다.
    """
    span = (n_windows - 1) * spacing_days + window_days
    return span / window_days


def overlap_pct(spacing_days, window_days):
    """이웃한 두 창이 몇 % 겹치나."""
    return max(0.0, (window_days - spacing_days) / window_days * 100)


def coin_at_least(k, n):
    """공정한 동전 n번에 k번 이상 앞면일 확률."""
    return sum(math.comb(n, i) for i in range(k, n + 1)) / 2 ** n


