HOLD_DAYS = (0, 5, 10, 20)      # 0 = 당일 종가
NEED_T = 2.0                    # 이 값을 넘어야 우연이 아니라고 본다
TOP_DROP = 3                    # 큰 것 몇 개를 빼고 다시 보나
BASE_DI = 250


def hold_return(panel, dpos, trade, n, fee=R.FEE_ROUND_TRIP):
    """실제 매수가로 사서 n거래일 뒤 종가에 팔았다면 (n=0 은 당일).

    매수가는 실제 체결가를 그대로 쓴다. 바꾸면 '그때 안 샀으면' 을 재는
    것이 되어 질문이 달라진다.
    """
    di = dpos.get(trade["buy_t"].strftime("%Y%m%d"))
    s = panel.get(trade["code"])
    if di is None or s is None:
        return None
    j = s.pos.get(di + n)
    if j is None or not trade["buy"]:
        return None
    return (s.close[j] / trade["buy"] - 1) * 100 - fee


def matched(panel, dpos, done, holds=HOLD_DAYS):
    """모든 보유기간에서 값이 나오는 거래만. 표본을 같게 맞춘다.

    안 맞추면 88건 대 71건 대 43건을 비교하게 되고, 차이가 규칙 때문인지
    표본 때문인지 모른다.
    """
    return [t for t in done
            if all(hold_return(panel, dpos, t, n) is not None for n in holds)]


def summary(vals):
    """(승률%, 평균, 합계, 중앙)."""
    if not vals:
        return (0.0, 0.0, 0.0, 0.0)
    w = sum(1 for x in vals if x > 0)
    return (w / len(vals) * 100, st.mean(vals), sum(vals), st.median(vals))


def tstat(vals):
    """(표본수, 평균, 표준편차, 표준오차, t). 표본이 2 미만이면 0."""
    n = len(vals)
    if n < 2:
        return (n, 0.0, 0.0, 0.0, 0.0)
    m, sd = st.mean(vals), st.pstdev(vals)
    se = sd / n ** 0.5
    return (n, m, sd, se, m / se if se else 0.0)


def drop_top(vals, k=TOP_DROP):
    """제일 큰 k 개를 뺀 평균. 몇 건이 전부를 만들었는지 보는 장치."""
    if len(vals) <= k:
        return 0.0
    return st.mean(sorted(vals)[:-k])


def proven(vals, need_t=NEED_T, k=TOP_DROP):
    """채택해도 되나. t 를 넘고, 큰 것 몇 개를 빼도 양수여야 한다.

    둘을 같이 요구하는 이유: t 만 보면 소수의 큰 값이 만든 평균을
    통과시킬 수 있다. 실제로 이번 43건이 그 모양이었다 (t=1.36 이고,
    상위 3건을 빼면 +0.647% 가 +0.072% 로 주저앉는다).
    """
    _n, m, _sd, _se, t = tstat(vals)
    return abs(t) >= need_t and m > 0 and drop_top(vals, k) > 0


def main():
    dates, panel = S.load_panel()
    dpos = {d: i for i, d in enumerate(dates)}
    done, _open = R.pair_fifo(R.load_trades())
    if not done:
        print("[!] 실거래 기록을 읽을 수 없습니다.")
        return 1
    base = matched(panel, dpos, done)
    if len(base) < 10:
        print(f"[!] 비교 가능한 거래가 {len(base)}건뿐입니다.")
        return 1

    print(f"\n=== 같은 {len(base)}건, 청산 규칙만 바꾸면 ===")
    print(f"{'규칙':<24}{'승률':>8}{'평균%':>9}{'합계%p':>10}{'중앙%':>9}")
    wr, m, s, md = summary([t["net"] for t in base])
    print(f"{'실제 (손절/익절)':<24}{wr:>7.1f}%{m:>+9.3f}{s:>+10.1f}{md:>+9.3f}")
    curves = {}
    for n in HOLD_DAYS:
        v = [hold_return(panel, dpos, t, n) for t in base]
        curves[n] = v
        wr, m, s, md = summary(v)
        lab = "규칙 없이 당일 종가" if n == 0 else f"{n}거래일 보유"
        print(f"{lab:<24}{wr:>7.1f}%{m:>+9.3f}{s:>+10.1f}{md:>+9.3f}")

    v = curves[0]
    n, m, sd, se, t = tstat(v)
    print(f"\n=== '당일 종가' 를 채택해도 되나 ===")
    print(f"  {n}건, 평균 {m:+.3f}%, 표준편차 {sd:.3f}%, 표준오차 {se:.3f}%")
    print(f"  t = {t:.2f}  (기준 |t| >= {NEED_T})")
    print(f"  95% 구간 대략 {m - 2 * se:+.3f}% ~ {m + 2 * se:+.3f}%")
    print(f"  상위 {TOP_DROP}건을 빼면 평균 {drop_top(v):+.3f}%")
    print(f"  => {'채택' if proven(v) else '유망하지만 미검증 (채택 안 함)'}")

    print(f"\n=== 오래 들면 나빠지는가 (종목이 고변동이었다는 뜻) ===")
    for n_ in HOLD_DAYS[1:]:
        _n, mm, _sd, _se, tt = tstat(curves[n_])
        print(f"  {n_:>2}거래일  평균 {mm:+.3f}%  t = {tt:+.2f}")

    print(f"\n=== 기준선: 같은 기간 저변동 10종목 / 120일 ===")
    d0 = dpos[min(x["buy_t"].strftime("%Y%m%d") for x in base)]
    d1 = dpos[max(x["buy_t"].strftime("%Y%m%d") for x in base)]
    order = K.ranks(dates, panel, BASE_DI)
    end = min(d1 + 21, len(dates))
    c, _i = K.run(dates, panel, order, 120, d0, 10, upto=end)
    print(f"  {dates[d0]} ~ {dates[end - 1]} ({len(c)}거래일)  "
          f"{(c[-1] / K.CAPITAL - 1) * 100:+.2f}%")
    print("  이 값이 '당일 청산' 을 채점할 때의 기준선이다.")

    print(f"\n대책: 손절/익절은 끈다(증거 둘). 고변동을 길게 안 든다(증거 둘).")
    print(f"      '저변동 + 당일 청산' 은 10분봉으로 새로 잰다 (미검증).")
    return 0


